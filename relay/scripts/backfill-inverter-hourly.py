def main():
    readings = []
    current_date = None
    cumulative = 0.0

    for date_str, hour, kwh, power_w in DATA:
        if date_str != current_date:
            current_date = date_str
            cumulative = 0.0
        cumulative += kwh

        # Parse date + hour in Budapest timezone → epoch ms
        dt = datetime.strptime(f"{date_str} {hour:02d}:00:00", "%Y-%m-%d %H:%M:%S")
        dt = dt.replace(tzinfo=BUDAPEST_TZ)
        timestamp = int(dt.timestamp() * 1000)

        readings.append({
            "timestamp": timestamp,
            "activePowerW": power_w,
            "dailyEnergyKwh": round(cumulative, 3)
        })

    payload = {
        "homeId": HOME_ID,
        "p1Readings": [],
        "inverterReadings": readings
    }

    print(f"Sending {len(readings)} inverter readings to relay...")
    print(f"Date range: {DATA[0][0]} to {DATA[-1][0]}")

    body = json.dumps(payload).encode("utf-8")
    req = urllib.request.Request(
        f"{RELAY_URL}/api/energy/{HOME_ID}/ingest",
        data=body,
        headers={
            "Content-Type": "application/json",
            "Authorization": f"Bearer {SYNC_TOKEN}",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=30) as resp:
            result = resp.read().decode()
            print(f"Response ({resp.status}): {result}")
            print("Done!")
    except urllib.error.HTTPError as e:
        print(f"HTTP Error {e.code}: {e.read().decode()}")
    except Exception as e:
        print(f"Error: {e}")

if __name__ == "__main__":
    main()
